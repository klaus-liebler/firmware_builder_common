using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace FirmwareBuilder.Common;

// The command catalog of a firmware's browser terminal (rtoos rtos/terminal): C# schema files
// (classes with [TerminalCommand], attributes in TerminalSchemaAttributes.cs) -> terminal_commands.hh
// (the firmware: a handler per command, an answer per lookup, both checked at compile time) and
// terminal-commands.ts (the web app: completion, help, parameter tooltip). The schema is read
// syntax-only with Roslyn, like UniversalRegisterAccess and BestBinaryBuffers: attributes by name.
// Projektspezifisch ist nur, wo das Schema liegt und wohin generiert wird.
public static partial class TerminalCatalog
{
	public sealed class Value
	{
		public string value { get; set; } = "";
		public string doc { get; set; } = "";
	}

	public sealed class Param
	{
		public string name { get; set; } = "";
		public string doc { get; set; } = "";
		public bool optional { get; set; }
		public List<Value>? values { get; set; }
		public string? lookup { get; set; }
		public string? source { get; set; }
	}

	public sealed class Command
	{
		public string name { get; set; } = "";
		public string doc { get; set; } = "";
		public bool client { get; set; }
		public List<Param> @params { get; set; } = [];
	}

	public sealed class Lookup
	{
		public string name { get; set; } = "";
		public string doc { get; set; } = "";
	}

	public sealed class Catalog
	{
		public List<Lookup> lookups { get; set; } = [];
		public List<Command> commands { get; set; } = [];
	}

	private static readonly string[] Sources = ["commands", "registers"];
	private static readonly HashSet<string> CppKeywords = ["and", "auto", "bool", "break", "case", "catch", "char", "class",
		"const", "continue", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false",
		"float", "for", "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "not", "operator",
		"or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static", "struct",
		"switch", "template", "this", "throw", "true", "try", "typedef", "typename", "union", "unsigned", "using",
		"virtual", "void", "volatile", "while", "xor"];

	[GeneratedRegex("^[a-z][a-z0-9_]*$")]
	private static partial Regex Identifier();

	[GeneratedRegex("<[^>]*>")]
	private static partial Regex XmlTag();

	public static void Generate(IBuildContext ctx, string schemaDir, string cppOutputDir, string tsOutputDir)
	{
		var catalog = Parse(schemaDir);
		Validate(catalog, schemaDir);
		var schema = Path.GetRelativePath(ctx.RootDir, schemaDir).Replace('\\', '/');
		var origin = $"// GENERATED by FirmwareBuilder.Common (TerminalCatalog) from {schema}/*.cs -- do not edit.\n";
		Directory.CreateDirectory(cppOutputDir);
		Directory.CreateDirectory(tsOutputDir);
		WriteIfChanged(Path.Combine(cppOutputDir, "terminal_commands.hh"), origin + Cpp(catalog));
		WriteIfChanged(Path.Combine(tsOutputDir, "terminal-commands.ts"), origin + TypeScript(catalog));
		Console.WriteLine($"{catalog.commands.Count} Befehl(e), {catalog.lookups.Count} Lookup(s) aus {schemaDir} -> {cppOutputDir} / {tsOutputDir}");
	}

	/// <summary>Commands in file order (by name), then declaration order; the one [TerminalLookups] enum.</summary>
	public static Catalog Parse(string schemaDir)
	{
		var files = Directory.GetFiles(schemaDir, "*.cs").Order(StringComparer.Ordinal).ToList();
		if (files.Count == 0) throw new InvalidOperationException($"{schemaDir}: no *.cs schema files");
		var catalog = new Catalog();
		bool lookupsSeen = false;
		foreach (var file in files)
		{
			var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(file), path: file);
			var errors = tree.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
			if (errors.Count > 0) throw new InvalidOperationException($"{file}: syntax errors\n  " + string.Join("\n  ", errors));
			foreach (var type in tree.GetCompilationUnitRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
			{
				var where = $"{file}: {type.Identifier.ValueText}";
				if (type is EnumDeclarationSyntax e && Attribute(e.AttributeLists, "TerminalLookups") is not null)
				{
					if (lookupsSeen) throw new InvalidOperationException($"{where}: a second [TerminalLookups] enum");
					lookupsSeen = true;
					catalog.lookups.AddRange(e.Members.Select(m => new Lookup { name = m.Identifier.ValueText, doc = Doc(m) }));
				}
				else if (type is ClassDeclarationSyntax c && Attribute(c.AttributeLists, "TerminalCommand") is { } command)
				{
					catalog.commands.Add(ParseCommand(c, command, where));
				}
			}
		}
		return catalog;
	}

	private static Command ParseCommand(ClassDeclarationSyntax c, AttributeSyntax attribute, string where)
	{
		void Fail(string what) => throw new InvalidOperationException($"{where}: {what}");
		var command = new Command
		{
			name = c.Identifier.ValueText,
			doc = Doc(c),
			client = Arguments(attribute).TryGetValue("Client", out var client) && client.IsKind(SyntaxKind.TrueLiteralExpression),
		};
		foreach (var member in c.Members)
		{
			if (member is not FieldDeclarationSyntax field) { Fail($"only fields (the parameters) expected, not '{member}'"); return command; }
			var optional = field.Declaration.Type is NullableTypeSyntax;
			var type = field.Declaration.Type is NullableTypeSyntax n ? n.ElementType : field.Declaration.Type;
			if (type.ToString() != "string") Fail($"parameter type string (or string? for an optional one) expected, not '{field.Declaration.Type}'");
			foreach (var variable in field.Declaration.Variables)
			{
				var param = new Param { name = variable.Identifier.ValueText, doc = Doc(field), optional = optional };
				foreach (var a in field.AttributeLists.SelectMany(l => l.Attributes))
				{
					var args = Arguments(a, "value", "doc");
					switch (ShortName(a))
					{
						case "Value":
							(param.values ??= []).Add(new Value
							{
								value = StringLiteral(args, "value", where) ?? "",
								doc = StringLiteral(args, "doc", where) ?? "",
							});
							break;
						case "Lookup":
							param.lookup = EnumMember(a, where);
							break;
						case "Source":
							param.source = EnumMember(a, where);
							break;
						default:
							Fail($"unknown attribute [{a.Name}] at parameter '{param.name}'");
							break;
					}
				}
				command.@params.Add(param);
			}
		}
		return command;
	}

	private static string ShortName(AttributeSyntax a)
	{
		var name = a.Name.ToString();
		name = name[(name.LastIndexOf('.') + 1)..];
		return name.EndsWith("Attribute", StringComparison.Ordinal) ? name[..^"Attribute".Length] : name;
	}

	private static AttributeSyntax? Attribute(SyntaxList<AttributeListSyntax> lists, string shortName) =>
		lists.SelectMany(l => l.Attributes).FirstOrDefault(a => ShortName(a) == shortName);

	/// <summary>Named arguments by name, positional ones by `positional` in order.</summary>
	private static Dictionary<string, ExpressionSyntax> Arguments(AttributeSyntax a, params string[] positional)
	{
		var result = new Dictionary<string, ExpressionSyntax>(StringComparer.Ordinal);
		int i = 0;
		foreach (var arg in a.ArgumentList?.Arguments ?? [])
		{
			var name = arg.NameEquals?.Name.Identifier.ValueText ?? arg.NameColon?.Name.Identifier.ValueText
				?? (i < positional.Length ? positional[i++] : throw new InvalidOperationException($"too many arguments in [{a}]"));
			result[name] = arg.Expression;
		}
		return result;
	}

	private static string? StringLiteral(Dictionary<string, ExpressionSyntax> args, string name, string where) =>
		!args.TryGetValue(name, out var e) ? null
			: e is LiteralExpressionSyntax { Token.Value: string s } ? s
			: throw new InvalidOperationException($"{where}: {name} must be a string literal, not '{e}'");

	// [Lookup(Lookup.inputs)], [Source(Source.registers)]: the member name
	private static string EnumMember(AttributeSyntax a, string where) =>
		a.ArgumentList?.Arguments is [{ Expression: MemberAccessExpressionSyntax m }] ? m.Name.Identifier.ValueText
			: throw new InvalidOperationException($"{where}: [{a}] expects one enum member, e.g. [Lookup(Lookup.pins)]");

	// the /// summary directly above a declaration, tags stripped, lines joined
	private static string Doc(SyntaxNode node)
	{
		var doc = node.GetLeadingTrivia().Select(t => t.GetStructure()).OfType<DocumentationCommentTriviaSyntax>().FirstOrDefault();
		if (doc is null) return "";
		var lines = XmlTag().Replace(doc.Content.ToFullString(), " ").Split('\n')
			.Select(l => l.Trim().TrimStart('/').Trim()).Where(l => l.Length > 0);
		return WebUtility.HtmlDecode(string.Join(" ", lines));
	}

	public static string Usage(Command c) =>
		string.Join(" ", [c.name, .. c.@params.Select(p => p.optional ? $"[<{p.name}>]" : $"<{p.name}>")]);

	private static void Validate(Catalog catalog, string file)
	{
		void Fail(string what) => throw new InvalidOperationException($"{file}: {what}");
		void Name(string kind, string name)
		{
			if (!Identifier().IsMatch(name) || CppKeywords.Contains(name))
				Fail($"{kind} '{name}': lower-case identifier expected (and no C++ keyword)");
		}

		var lookups = new HashSet<string>();
		foreach (var l in catalog.lookups)
		{
			Name("lookup", l.name);
			if (!lookups.Add(l.name)) Fail($"lookup '{l.name}' twice");
		}
		if (lookups.Count > 255) Fail("more than 255 lookups");

		var commands = new HashSet<string>();
		foreach (var c in catalog.commands)
		{
			Name("command", c.name);
			if (!commands.Add(c.name)) Fail($"command '{c.name}' twice");
			if (c.doc.Length == 0) Fail($"command '{c.name}': doc missing");
			bool optionalSeen = false;
			foreach (var p in c.@params)
			{
				var where = $"command '{c.name}', parameter '{p.name}'";
				if (p.name.Length == 0 || p.doc.Length == 0) Fail($"{where}: name and doc required");
				if (optionalSeen && !p.optional) Fail($"{where}: a required parameter after an optional one");
				optionalSeen |= p.optional;
				int kinds = (p.values is null ? 0 : 1) + (p.lookup is null ? 0 : 1) + (p.source is null ? 0 : 1);
				if (kinds > 1) Fail($"{where}: at most one of values, lookup, source");
				if (p.lookup is not null && !lookups.Contains(p.lookup)) Fail($"{where}: unknown lookup '{p.lookup}'");
				if (p.source is not null && !Sources.Contains(p.source))
					Fail($"{where}: unknown source '{p.source}' (known: {string.Join(", ", Sources)})");
				if (p.values is not null)
				{
					if (p.values.Count == 0) Fail($"{where}: empty values");
					if (p.values.Any(v => v.value.Length == 0 || v.value.Contains(' '))) Fail($"{where}: a value is empty or contains a space");
					if (p.values.Select(v => v.value).Distinct().Count() != p.values.Count) Fail($"{where}: a value twice");
				}
			}
		}
	}

	private static string CppString(string s) =>
		"\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

	private static string Cpp(Catalog catalog)
	{
		var device = catalog.commands.Where(c => !c.client).ToList();
		var sb = new StringBuilder();
		sb.Append("""
			// The commands the device runs (the client ones, e.g. help and clear, stay in the browser) and the
			// value lookups the browser asks for (terminal.LookupRequest.lookup = Lookup).
			#pragma once

			#include <array>
			#include <cstddef>
			#include <cstdint>
			#include <string_view>

			namespace terminal_catalog {

			""");
		sb.Append("\nenum class Command : std::uint8_t {\n");
		foreach (var c in device) sb.Append($"    {c.name},\n");
		sb.Append("};\n\n");
		sb.Append("struct CommandInfo {\n    Command id;\n    std::string_view name;\n    std::string_view usage;\n};\n\n");
		sb.Append($"inline constexpr std::array<CommandInfo, {device.Count}> commands{{{{\n");
		foreach (var c in device) sb.Append($"    {{Command::{c.name}, {CppString(c.name)}, {CppString(Usage(c))}}},\n");
		sb.Append("}};\n\n");
		sb.Append("enum class Lookup : std::uint8_t {\n");
		foreach (var l in catalog.lookups) sb.Append($"    {l.name},  // {l.doc}\n");
		sb.Append("};\n\n");
		sb.Append($"inline constexpr std::size_t lookup_count = {catalog.lookups.Count};\n\n");
		sb.Append("}  // namespace terminal_catalog\n");
		return sb.ToString();
	}

	private static string TypeScript(Catalog catalog)
	{
		var lookupIds = catalog.lookups.Select((l, i) => (l.name, i)).ToDictionary(x => x.name, x => x.i);
		var options = new JsonSerializerOptions
		{
			WriteIndented = true,
			DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
			Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
		};
		var commands = catalog.commands.Select(c => new
		{
			c.name,
			c.doc,
			c.client,
			usage = Usage(c),
			@params = c.@params.Select(p => new
			{
				p.name,
				p.doc,
				p.optional,
				p.values,
				lookup = p.lookup is null ? (int?)null : lookupIds[p.lookup],
				p.source,
			}),
		});
		var sb = new StringBuilder();
		sb.Append("""

			export interface TerminalValue {
				value: string;
				doc: string;
			}

			/** Values computed in the browser: command names, register addresses of the bank given before. */
			export type TerminalSource = "commands" | "registers";

			export interface TerminalParam {
				name: string;
				doc: string;
				optional: boolean;
				values?: TerminalValue[];
				/** fetched live from the device: terminal.LookupRequest.lookup */
				lookup?: number;
				source?: TerminalSource;
			}

			export interface TerminalCommand {
				name: string;
				doc: string;
				/** runs in the browser (help, clear) */
				client: boolean;
				usage: string;
				params: TerminalParam[];
			}

			export interface TerminalLookup {
				name: string;
				doc: string;
			}


			""");
		sb.Append("export const TERMINAL_LOOKUPS: readonly TerminalLookup[] = ");
		sb.Append(JsonSerializer.Serialize(catalog.lookups, options)).Append(";\n\n");
		sb.Append("export const TERMINAL_COMMANDS: readonly TerminalCommand[] = ");
		sb.Append(JsonSerializer.Serialize(commands, options)).Append(";\n");
		return sb.ToString().Replace("\r\n", "\n");
	}

	private static void WriteIfChanged(string path, string content)
	{
		content = content.Replace("\r\n", "\n");
		if (File.Exists(path) && File.ReadAllText(path) == content) return;
		File.WriteAllText(path, content, new UTF8Encoding(false));
		Console.WriteLine($"generated {path}");
	}
}
